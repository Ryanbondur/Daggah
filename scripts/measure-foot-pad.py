#!/usr/bin/env python3
"""Measure how much empty / non-foot art sits below each stage sprite's feet.

Writes src/stage/footPad.ts. Run after `npm run art` if sprites change:
    python3 scripts/measure-foot-pad.py

footPad = fraction of the texture height between the sprite's contact row and the
bottom edge. The contact row is the lowest row whose opaque coverage is at least
ROW_COVERAGE of the sprite width, so thin weapon tips, tails and wisps that dangle
below the feet do not pull the sprite up. Floating foes are measured to their lowest
opaque pixel instead (FLOATING).
"""
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SPRITES = ROOT / "public" / "assets" / "sprites"
OUT = ROOT / "src" / "stage" / "footPad.ts"

ALPHA_MIN = 40
ROW_COVERAGE = 0.08
FLOATING = {
    "enemy-ash-bat",
    "enemy-echo-wisp",
    "enemy-frost-wisp",
    "enemy-rift-shade",
    "enemy-nightscar-shade",
    "boss-void-herald",
}


def foot_pad(name: str, alpha: np.ndarray) -> float:
    h, w = alpha.shape
    solid = alpha > ALPHA_MIN
    if name in FLOATING:
        rows = np.where(solid.any(axis=1))[0]
    else:
        rows = np.where(solid.sum(axis=1) / w >= ROW_COVERAGE)[0]
    return round((h - 1 - rows.max()) / h, 3)


def main() -> None:
    lines = []
    for path in sorted(SPRITES.glob("*.webp")):
        alpha = np.asarray(Image.open(path).convert("RGBA"))[:, :, 3]
        lines.append(f"  '{path.stem}': {foot_pad(path.stem, alpha)},")
    body = "\n".join(lines)
    OUT.write_text(
        "// Generated by scripts/measure-foot-pad.py — do not edit by hand.\n"
        "/** Fraction of each sprite texture's height below its feet (contact row). */\n"
        f"export const FOOT_PAD: Readonly<Record<string, number>> = {{\n{body}\n}};\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({len(lines)} sprites)")


if __name__ == "__main__":
    main()
