/**
 * Bundle each hosted API route into a single self-contained ESM file under api/.
 *
 * The Cursor publish host packs each api/* entry without reliably including
 * sibling folders (api/_lib) or ../src — relative local imports then crash at
 * load with FUNCTION_INVOCATION_FAILED. npm packages stay external.
 *
 * Edit api/_lib/* (and api/_entries/*), then run: npm run bundle:api
 */
import { build } from 'esbuild';
import { mkdir, unlink, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const routes = [
  { entry: 'api/_entries/daggah-auth.ts', outfile: 'api/daggah-auth.js' },
  { entry: 'api/_entries/daggah-save.ts', outfile: 'api/daggah-save.js' },
  { entry: 'api/_entries/daggah-clan-board.ts', outfile: 'api/daggah-clan-board.js' },
];

async function bundleOne({ entry, outfile }) {
  const result = await build({
    absWorkingDir: root,
    entryPoints: [entry],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: ['node20'],
    packages: 'external',
    write: false,
    logLevel: 'silent',
    banner: {
      js: '/* auto-generated by scripts/bundle-api.mjs — do not edit; change api/_lib and re-bundle */\n',
    },
  });
  const file = result.outputFiles?.[0];
  if (!file) throw new Error(`esbuild produced no output for ${entry}`);
  const outPath = join(root, outfile);
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, file.text, 'utf8');
  console.log(`bundled ${entry} → ${outfile} (${file.text.length} bytes)`);
}

for (const route of routes) {
  await bundleOne(route);
}

for (const stale of ['api/daggah-auth.ts', 'api/daggah-save.ts', 'api/daggah-clan-board.ts']) {
  try {
    await unlink(join(root, stale));
    console.log(`removed stale ${stale}`);
  } catch (error) {
    if (error && typeof error === 'object' && 'code' in error && error.code !== 'ENOENT') {
      throw error;
    }
  }
}
